import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadScenarios, type Scenario } from './schema';

const dir = join(import.meta.dir, '..', '..', 'scenarios');
export function scenarioIndex(scenarios: Scenario[]): string {
  const rows = scenarios.map(s => `| ${s.id} | ${s.name} | ${s.category} | ${s.guardrails.join(', ')} | ${s.env_needs.join(', ')} | ${s.merged_from?.join(', ') ?? ''} |`);
  return ['# Scenario index', '', 'Generated by `bun run scenarios:index` from the scenario JSON files.', '', '| ID | Scenario | Category | Guardrails | Environment | Merged from |', '|---|---|---|---|---|---|', ...rows, ''].join('\n');
}

if (import.meta.main) writeFileSync(join(dir, 'README.md'), scenarioIndex(loadScenarios(dir)));
